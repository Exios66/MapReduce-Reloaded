#!/bin/sh
# Generates Go and Python code from the .proto files in proto/.
#
# Both languages use the same protoc compiler: the one bundled with the
# grpcio-tools Python package. That means the only things needed are
# `pip install -e "python[dev]"` and `make tools`, with no separate protoc install.
#
# Output (committed to git, so users of the code never need these tools):
#   go/gen/mapreduce/v1/                     Go messages + gRPC client/server
#   python/mapreduce_reloaded/gen/mapreduce/v1/  Python messages + gRPC stubs
set -eu

cd "$(dirname "$0")/.."
ROOT=$(pwd)
TOOLS="$ROOT/.tools/bin"
PYTHON=${PYTHON:-python3}
GO_OUT="$ROOT/go/gen"
PY_OUT="$ROOT/python/mapreduce_reloaded/gen"
PROTOS=$(find proto -name '*.proto' | sort)

# Generate into a temporary directory and only replace the real output
# directories at the end, so a failed run leaves the committed code intact.
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
FINAL_GO_OUT=$GO_OUT
FINAL_PY_OUT=$PY_OUT
GO_OUT="$TMP/go"
PY_OUT="$TMP/py"
mkdir -p "$GO_OUT" "$PY_OUT"

# Go: protoc-gen-go writes the message types, protoc-gen-go-grpc the
# service interfaces. paths=source_relative puts files under go/gen/
# mirroring proto/ instead of under the full Go import path.
"$PYTHON" -m grpc_tools.protoc -I proto \
  --plugin=protoc-gen-go="$TOOLS/protoc-gen-go" \
  --plugin=protoc-gen-go-grpc="$TOOLS/protoc-gen-go-grpc" \
  --go_out="$GO_OUT" --go_opt=paths=source_relative \
  --go-grpc_out="$GO_OUT" --go-grpc_opt=paths=source_relative \
  $PROTOS

# Python: messages (_pb2.py), type stubs for editors (_pb2.pyi), and gRPC
# stubs (_pb2_grpc.py).
"$PYTHON" -m grpc_tools.protoc -I proto \
  --python_out="$PY_OUT" --pyi_out="$PY_OUT" --grpc_python_out="$PY_OUT" \
  $PROTOS

# protoc writes Python imports as if proto/ were the top of the Python path
# ("from mapreduce.v1 import types_pb2"). Our generated code lives inside the
# mapreduce_reloaded package, so rewrite those imports to point there.
find "$PY_OUT" -name '*.py' -o -name '*.pyi' | while read -r f; do
  sed -i.bak 's/^from mapreduce\.v1 import/from mapreduce_reloaded.gen.mapreduce.v1 import/' "$f"
  rm -f "$f.bak"
done

# Make every generated directory an importable Python package.
for d in "$PY_OUT" "$PY_OUT/mapreduce" "$PY_OUT/mapreduce/v1"; do
  echo '"""Generated by scripts/gen-proto.sh. Do not edit."""' > "$d/__init__.py"
done

rm -rf "$FINAL_GO_OUT" "$FINAL_PY_OUT"
mv "$GO_OUT" "$FINAL_GO_OUT"
mv "$PY_OUT" "$FINAL_PY_OUT"
echo "generated: $FINAL_GO_OUT $FINAL_PY_OUT"
